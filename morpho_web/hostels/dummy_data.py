def bed_counts(room):
    total = len(room["beds"])
    vacant = sum(1 for bed in room["beds"] if bed["status"] == "vacant")
    return {"total": total, "vacant": vacant, "occupied": total - vacant}


def hostel_counts(hostel):
    total = sum(len(room["beds"]) for room in hostel["rooms"])
    vacant = sum(bed_counts(room)["vacant"] for room in hostel["rooms"])
    return {"total": total, "vacant": vacant, "occupied": total - vacant}


